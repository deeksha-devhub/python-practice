#Numeric datatype
a = 15
b = 12.5
c = 'A'
d = "Siva"
e = True
f = 3 + 9j

print(a)
print(type(a))
print(b)
print(type(b))
print(c)
print(type(c))
print(d)
print(type(d))
print(e)
print(type(e))
print(f)
print(type(f))

#Sequence datatype
list = [2,4,'a',2.5,True]
tuple = (9,6,4,8,2,3,'a')

print(list)
print(type(list))
print(tuple)
print(type(tuple))

#Set datatype
set = {3,4,5,6,7,7} #duplicate 7 are ignored

print(set)
print(type(set))

#Dictionary
dict = {'name':'Asha','roll':101,'dept':'cse'}

print(dict)
print(type(dict))